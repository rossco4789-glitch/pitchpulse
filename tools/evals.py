#!/usr/bin/env python3
"""
evals.py — PitchPulse self-improving evaluation ledger
=======================================================
Usage:
    python tools/evals.py --digest [--top N]    # rewrite data/evals/learnings.md, print top N open issues
    python tools/evals.py --replay              # re-run validators on frozen cases (exit 2 if one slips through)
    python tools/evals.py --resolve FP "note"   # mark a fingerprint fixed

Library API (stdlib only):
    record(tool, check, severity, key, detail, run_id, sample=None) -> severity
    gate(run_id) -> list of unresolved ERROR findings for that run

Files:
    data/evals/ledger.jsonl     append-only run history (gitignored, local)
    data/evals/cases/{fp}.json  frozen bad input each validator must keep catching (tracked)
    data/evals/learnings.md     generated digest, sorted by recurrence (tracked)
"""

import hashlib
import json
import sys
import time
from pathlib import Path

ROOT   = Path(__file__).resolve().parents[1]
EVALS  = ROOT / "data" / "evals"
LEDGER = EVALS / "ledger.jsonl"
CASES  = EVALS / "cases"
LEARN  = EVALS / "learnings.md"


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S")


def _append(row: dict) -> None:
    EVALS.mkdir(parents=True, exist_ok=True)
    with LEDGER.open("a", encoding="utf-8") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def fingerprint(tool: str, check: str, key: str) -> str:
    """Stable id for a *category* of failure — key must not contain match-specific detail."""
    return hashlib.sha1(f"{tool}|{check}|{key}".encode("utf-8")).hexdigest()[:12]


def history() -> dict:
    """Fold the ledger into per-fingerprint state."""
    state: dict = {}
    if not LEDGER.exists():
        return state
    for line in LEDGER.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        s = state.setdefault(r["fp"], {"count": 0, "runs": set(), "error_runs": set(), "resolved": False})
        if r["severity"] == "RESOLVED":
            s["resolved"], s["note"] = True, r.get("detail", "")
            s["error_runs"] = set()
            continue
        s.update({k: v for k, v in r.items() if k not in ("ts",)})
        s["count"] += 1
        s["runs"].add(r.get("run_id"))
        if r["severity"] == "ERROR":
            s["error_runs"].add(r.get("run_id"))
        s["resolved"] = False
    return state


def record(tool: str, check: str, severity: str, key: str, detail: str,
           run_id: str, sample=None) -> str:
    """Log one finding. Returns the severity the caller must honour (escalated on regression)."""
    fp = fingerprint(tool, check, key)
    prior = history().get(fp)
    if prior and prior["resolved"]:
        severity = "ERROR"
        detail = f"REGRESSION of resolved issue ({prior.get('note', '')}): {detail}"
    _append({"ts": _now(), "run_id": run_id, "tool": tool, "check": check,
             "severity": severity, "key": key, "fp": fp, "detail": detail})
    case = CASES / f"{fp}.json"
    if sample is not None and not case.exists():
        CASES.mkdir(parents=True, exist_ok=True)
        case.write_text(json.dumps({"fp": fp, "tool": tool, "check": check, "key": key, "input": sample},
                                   indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return severity


def gate(run_id: str) -> list[dict]:
    """Unresolved ERROR findings logged against run_id."""
    return [s for s in history().values() if not s["resolved"] and run_id in s["error_runs"]]


def replay() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import tagger_sanity

    detectors = {
        "tagger_sanity": lambda c: any(f[1] == c["check"] for f in tagger_sanity.run_checks(c["input"])),
    }
    cases = sorted(CASES.glob("*.json"))
    missed, skipped = [], 0
    for p in cases:
        c = json.loads(p.read_text(encoding="utf-8"))
        detect = detectors.get(c["tool"])
        if detect is None:
            skipped += 1
        elif not detect(c):
            missed.append(f"{p.stem}  {c['tool']}:{c['check']} [{c.get('key', '')}] no longer detected")
    if missed:
        print("Eval replay FAILED — validator no longer catches a frozen case:\n  " + "\n  ".join(missed),
              file=sys.stderr)
        sys.exit(2)
    print(f"Eval replay: {len(cases) - skipped}/{len(cases)} frozen cases still caught"
          + (f" ({skipped} skipped: no detector)" if skipped else ""))


def digest(top: int = 10) -> None:
    rows = sorted((s for s in history().values() if not s["resolved"] and "tool" in s),
                  key=lambda s: (-s["count"], s["fp"]))
    lines = ["# PitchPulse Learnings", "",
             "_Generated by `python tools/evals.py --digest` — close items with `--resolve`, do not hand-edit._", ""]
    if not rows:
        lines.append("No open issues.")
    lines += [f"- `{s['fp']}` x{s['count']} across {len(s['runs'])} run(s) · {s['severity']} · "
              f"{s['tool']}:{s['check']} [{s['key']}] — {s['detail']} (last run: {s['run_id']})"
              for s in rows]
    EVALS.mkdir(parents=True, exist_ok=True)
    LEARN.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:4 + top]))


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    except AttributeError:
        pass
    args = sys.argv[1:]
    if "--replay" in args:
        replay()
    elif "--resolve" in args:
        i = args.index("--resolve")
        if len(args) < i + 3:
            print('Usage: python tools/evals.py --resolve FP "note"', file=sys.stderr)
            sys.exit(2)
        fp, note = args[i + 1], args[i + 2]
        if fp not in history():
            print(f"Unknown fingerprint: {fp}", file=sys.stderr)
            sys.exit(2)
        _append({"ts": _now(), "fp": fp, "severity": "RESOLVED", "detail": note})
        print(f"Resolved {fp}: {note}")
    elif "--digest" in args or not args:
        digest(int(args[args.index("--top") + 1]) if "--top" in args else 10)
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == "__main__":
    main()
